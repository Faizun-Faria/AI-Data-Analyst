"""Explore the warehouse marts before writing the semantic layer (phase 3).

Metric and dimension definitions depend on facts about the modelled data: which issues
each product group has had across the CFPB's taxonomy changes, how company names appear,
how responses and relief are spread over time, and how long complaints take to reach the
company. This script answers those questions, read-only, from the marts that
`python run_pipeline.py transform` builds, and writes them to docs/06-semantic-profile.md.

    python scripts/explore_semantics.py
"""

from __future__ import annotations

import argparse
from datetime import datetime
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent.parent

# Brands whose naming we need to see, because questions will name them loosely
# ("Wells Fargo", "Chase"). Matched case-insensitively anywhere in the company name.
BRANDS = [
    "WELLS FARGO",
    "BANK OF AMERICA",
    "JPMORGAN",
    "CHASE",
    "CITI",
    "CAPITAL ONE",
    "DISCOVER",
    "SYNCHRONY",
    "EQUIFAX",
    "EXPERIAN",
    "TRANSUNION",
    "NAVIENT",
]

COMPLAINTS = """
    marts.fct_complaints as f
    join marts.dim_product as p using (product_key)
    join marts.dim_company as c using (company_key)
    join marts.dim_date as d on f.date_received = d.date_day
"""


def table(headers: list[str], rows) -> str:
    def cell(value) -> str:
        if value is None:
            return ""
        if isinstance(value, bool):
            return "yes" if value else "no"
        if isinstance(value, int):
            return f"{value:,}"
        if isinstance(value, float):
            return f"{value:,.1f}"
        return str(value).replace("|", "\\|").replace("\n", " ")

    lines = ["| " + " | ".join(headers) + " |", "|" + " --- |" * len(headers)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def build_report(conn: duckdb.DuckDBPyConnection) -> str:
    def q(sql: str, params: list | None = None) -> list[tuple]:
        return conn.execute(sql, params or []).fetchall()

    total = q("select count(*) from marts.fct_complaints")[0][0]
    out = [
        "# Semantic profile: what the marts hold",
        "",
        f"Generated by `scripts/explore_semantics.py` on {datetime.now():%Y-%m-%d %H:%M} from "
        f"{total:,} complaints in `marts.fct_complaints`. Don't edit by hand: re-run the "
        "script instead.",
    ]

    # 1. Volume by product group and year: shows taxonomy eras and partial years at a glance.
    rows = q(f"select p.product_group, d.year, count(*) from {COMPLAINTS} group by all")
    years = sorted({year for _, year, _ in rows})
    groups = sorted({group for group, _, _ in rows}, key=lambda g: (g is None, g))
    counts = {(group, year): n for group, year, n in rows}
    out += ["", "## 1. Complaints by product group and year", ""]
    out.append(
        table(
            ["Product group", *[str(y) for y in years]],
            [(g, *[counts.get((g, y), 0) for y in years]) for g in groups],
        )
    )

    # 2. Issues per product group, with the dates each issue was in use.
    out += ["", "## 2. Issues by product group", ""]
    out.append(
        table(
            ["Product group", "Issue", "Complaints", "First received", "Last received"],
            q(
                f"""
                select p.product_group, coalesce(f.issue, '(empty)'), count(*),
                       min(f.date_received), max(f.date_received)
                from {COMPLAINTS} group by all order by 1, 3 desc
                """
            ),
        )
    )

    # 3. Sub-issues where the showcase and MVP questions live.
    out += ["", "## 3. Sub-issues for bank accounts and credit cards", ""]
    out.append(
        table(
            ["Product group", "Issue", "Sub-issue", "Complaints", "First", "Last"],
            q(
                f"""
                select p.product_group, coalesce(f.issue, '(empty)'),
                       coalesce(f.sub_issue, '(empty)'), count(*),
                       min(f.date_received), max(f.date_received)
                from {COMPLAINTS}
                where p.product_group in ('Bank account', 'Credit card', 'Prepaid card')
                group by all order by 1, 2, 4 desc
                """
            ),
        )
    )

    # 4. Sub-products of the card products, to judge the Credit card mapping (D-018).
    out += ["", "## 4. Sub-products of the card products", ""]
    out.append(
        table(
            ["Product", "Sub-product", "Complaints", "First", "Last"],
            q(
                f"""
                select p.product, coalesce(p.sub_product, '(empty)'), count(*),
                       min(f.date_received), max(f.date_received)
                from {COMPLAINTS}
                where p.product in ('Credit card', 'Credit card or prepaid card', 'Prepaid card')
                group by all order by 1, 3 desc
                """
            ),
        )
    )

    # 5. Companies: the largest, and every name that contains a well-known brand.
    out += ["", "## 5. Companies", "", "Top 40 by complaints:", ""]
    out.append(
        table(
            ["Company", "Complaints", "First received", "Last received"],
            q(
                f"""
                select c.company_name, count(*), min(f.date_received), max(f.date_received)
                from {COMPLAINTS} group by all order by 2 desc limit 40
                """
            ),
        )
    )
    out += ["", "Names containing a well-known brand:", ""]
    brand_rows = []
    for brand in BRANDS:
        brand_rows += q(
            f"""
            select ?, c.company_name, count(*), min(f.date_received), max(f.date_received)
            from {COMPLAINTS}
            where upper(c.company_name) like '%' || ? || '%'
            group by all order by 3 desc
            """,
            [brand, brand],
        )
    out.append(table(["Brand", "Company name", "Complaints", "First", "Last"], brand_rows))

    # 6. How responses and relief are spread over time (open complaints cluster late).
    out += ["", "## 6. Company responses by year", ""]
    statuses = ["closed", "in progress", "untimely", "unknown"]
    reliefs = ["monetary", "non-monetary", "type not recorded", "none", "pending", "unknown"]
    by_year = q(
        f"""
        select d.year, f.response_status, f.relief_type, count(*)
        from {COMPLAINTS} group by all
        """
    )
    status_counts: dict = {}
    relief_counts: dict = {}
    for year, status, relief, n in by_year:
        status_counts[(year, status)] = status_counts.get((year, status), 0) + n
        relief_counts[(year, relief)] = relief_counts.get((year, relief), 0) + n
    out.append(
        table(
            ["Year", *statuses],
            [(str(y), *[status_counts.get((y, s), 0) for s in statuses]) for y in years],
        )
    )
    out += ["", "Relief type by year:", ""]
    out.append(
        table(
            ["Year", *reliefs],
            [(str(y), *[relief_counts.get((y, r), 0) for r in reliefs]) for y in years],
        )
    )

    # 7. Timeliness and the days from receipt to the company, by year.
    out += ["", "## 7. Timely responses and days to reach the company, by year", ""]
    out.append(
        table(
            [
                "Year",
                "Complaints",
                "% timely",
                "Median days to company",
                "90th percentile",
                "Max",
                "Sent before received",
            ],
            q(
                f"""
                select d.year::varchar, count(*),
                       100.0 * avg(f.is_timely_response::int),
                       median(f.date_sent_to_company - f.date_received)
                           filter (where not f.is_sent_before_received),
                       quantile_cont(f.date_sent_to_company - f.date_received, 0.9)
                           filter (where not f.is_sent_before_received),
                       max(f.date_sent_to_company - f.date_received),
                       count(*) filter (where f.is_sent_before_received)
                from {COMPLAINTS} group by all order by 1
                """
            ),
        )
    )

    # 8. Narratives and tags by year: coverage the analyst must not mistake for a trend.
    out += ["", "## 8. Narratives and tags by year", ""]
    out.append(
        table(
            ["Year", "Complaints", "% with narrative", "Older American", "Servicemember"],
            q(
                f"""
                select d.year::varchar, count(*), 100.0 * avg(f.has_narrative::int),
                       count(*) filter (where f.is_older_american),
                       count(*) filter (where f.is_servicemember)
                from {COMPLAINTS} group by all order by 1
                """
            ),
        )
    )
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Explore the marts for the semantic layer")
    parser.add_argument("--db", type=Path, default=ROOT / "data/warehouse/query_cf.duckdb")
    parser.add_argument("--out", type=Path, default=ROOT / "docs/06-semantic-profile.md")
    args = parser.parse_args(argv)

    conn = duckdb.connect(str(args.db), read_only=True)
    try:
        report = build_report(conn)
    except duckdb.CatalogException as exc:
        print(f"The marts aren't built yet ({str(exc).splitlines()[0]}).")
        print("Run: python run_pipeline.py transform")
        return 1
    finally:
        conn.close()

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report, encoding="utf-8")
    print(f"Report written to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
